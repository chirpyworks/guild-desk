import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
let html = await readFile(resolve(root,'dist/index.html'),'utf8');
const script = html.match(/<script[^>]+src="([^"]+)"[^>]*><\/script>/);
const css = html.match(/<link[^>]+href="([^"]+\.css)"[^>]*>/);
if (!script || !css) throw new Error('Expected one JS bundle and one stylesheet');
const js = await readFile(resolve(root,'dist',script[1]),'utf8');
const style = await readFile(resolve(root,'dist',css[1]),'utf8');
html = html.replace(script[0],()=>'<script type="module">'+js.replaceAll('</script','<\\/script')+'</script>');
html = html.replace(css[0],()=>'<style>'+style+'</style>');
const notices = await readFile(resolve(root,'THIRD_PARTY_NOTICES.md'),'utf8');
html = '<!--\n'+notices.replaceAll('--','—')+'\n-->\n'+html;
await mkdir(resolve(root,'release'),{recursive:true});
await writeFile(resolve(root,'release/guild-desk.html'),html);
await mkdir(resolve(root,'docs'),{recursive:true});
await writeFile(resolve(root,'docs/index.html'),html);
await writeFile(resolve(root,'docs/.nojekyll'),'');
console.log('release/guild-desk.html created; no runtime package or font downloads.');
